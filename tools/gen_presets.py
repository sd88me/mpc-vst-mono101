#!/usr/bin/env python3
"""The factory presets: tools/presets/*.json -> src/onex1/presets_factory.h ("name", "id=value ...", plain values; choices as
their index). Choice names are matched against OneX1Plugin.cpp's choiceParam lists, so a renamed choice fails here.
    python3 tools/gen_presets.py      (build-sdk.sh runs it)"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = open(os.path.join(ROOT, "src", "OneX1Plugin.cpp")).read()
CHOICES = {m.group(1): re.findall(r'"([^"]*)"', m.group(2))
           for m in re.finditer(r'choiceParam\("([a-z0-9_]+)",\s*"[^"]*",\s*\{([^}]*)\}', SRC)}
FLOATS = set(re.findall(r'slider\("([a-z0-9_]+)"', SRC)) | {"tune"}
SETS = ["sh101_manual.json", "mono101_originals.json"]   # in PRESET menu order, after Init


def value(key, v):
    if key in CHOICES:
        if v not in CHOICES[key]:
            sys.exit("%s: %r is not one of %s" % (key, v, CHOICES[key]))
        return str(CHOICES[key].index(v))
    if key not in FLOATS:
        sys.exit("unknown parameter %s" % key)
    return "%g" % float(v)


lines = []
for f in SETS:
    for p in json.load(open(os.path.join(ROOT, "tools", "presets", f)))["presets"]:
        assert len(p["name"]) <= 24, p["name"]
        body = " ".join("%s=%s" % (k, value(k, v)) for k, v in p["params"].items())
        lines.append('\t{"%s", "%s"},' % (p["name"], body))
out = """// Generated by tools/gen_presets.py from tools/presets/*.json: do not edit.
// The SH-101 Owner's Manual's 40 sample sounds (1982, transcribed from its patch charts), then Mono-101's own.
#pragma once

namespace onex1 {

struct FactoryPreset {
	const char *name;
	const char *values; // "id=value ...": plain values (choices as their index); the rest keep Init's
};

static const FactoryPreset kFactoryPresets[] = {
%s
};

constexpr int kNumFactoryPresets = int(sizeof kFactoryPresets / sizeof kFactoryPresets[0]);

} // namespace onex1
""" % "\n".join(lines)
open(os.path.join(ROOT, "src", "onex1", "presets_factory.h"), "w").write(out)
print("presets_factory.h: %d presets" % len(lines))
